"""Generate (or --check) tests/golden_corpus.py from live parser output.

    python -m scripts.emit_golden            # regenerate the golden data module
    python -m scripts.emit_golden --check    # exit 1 if the committed golden is stale

Run from the repo root: `scripts` and `tests` resolve as namespace packages
from the working directory, so no sys.path editing is needed.

There is no hand-transcription step: the emitter writes the data module the test
imports. `--check` compares DATA, not file text (it imports the committed GOLDEN
and diffs the dicts), so it is immune to any reformatting of the generated file
and prints exactly which fixture moved. `--check` is wired into `make check` and
CI, so a golden that no longer matches parser behaviour fails automatically.
Regeneration is deliberate: a diff to the golden is a parser behaviour change.

The record-to-tuple mapping lives in tests/golden_support.py (single source),
shared with the test. Pinned: ordered sequence, anomaly kind, anomaly stream
offset, each recovered ADU's (function_code, transaction_id). Not pinned:
anomaly detail strings, snippet bytes, non-identifying ADU fields. See GATES.md.
"""
import argparse
import importlib.util
from pathlib import Path

from tests.golden_support import compute_golden

REPO = Path(__file__).resolve().parent.parent
TARGET = REPO / "tests" / "golden_corpus.py"

_HEADER = '''"""GENERATED by scripts/emit_golden.py. Do not edit by hand.

Ordered parser-output signature per corpus fixture:
    ("anom", kind, stream_byte_offset) | ("adu", function_code, transaction_id)

Regenerate:  python -m scripts.emit_golden
Check:       python -m scripts.emit_golden --check   (run by `make check` and CI)
"""
'''


def render(golden: dict[str, tuple]) -> str:
    lines = [_HEADER, "GOLDEN: dict[str, tuple[tuple, ...]] = {"]
    for name, seq in golden.items():
        lines.append(f"    {name!r}: {seq!r},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def _load_committed() -> dict | None:
    if not TARGET.exists():
        return None
    spec = importlib.util.spec_from_file_location("_committed_golden", TARGET)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)  # data module: a dict literal, no side effects
    return mod.GOLDEN


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate or --check tests/golden_corpus.py")
    ap.add_argument("--check", action="store_true", help="exit 1 (with a diff) if the golden is stale")
    args = ap.parse_args(argv)

    current = compute_golden()

    if args.check:
        committed = _load_committed()
        if committed is None:
            print("FAIL: tests/golden_corpus.py is missing. Run: python -m scripts.emit_golden")
            return 1
        if committed == current:
            print(f"PASS: golden matches current parser output ({len(current)} fixtures).")
            return 0
        print("FAIL: golden is stale. Per-fixture differences (committed -> current):")
        for key in sorted(set(committed) | set(current)):
            c, n = committed.get(key), current.get(key)
            if c != n:
                print(f"  {key}:")
                print(f"      committed: {c}")
                print(f"      current:   {n}")
        print("If this change is intended: python -m scripts.emit_golden")
        return 1

    TARGET.write_text(render(current))
    print(f"wrote {TARGET.relative_to(REPO)} ({len(current)} fixtures)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
